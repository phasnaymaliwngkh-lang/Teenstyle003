-- เหตุผลเดียวกับ 20260913223800_add_check_constraints:
-- โค้ดอาจมีบั๊ก แต่ฐานข้อมูลต้องไม่ยอมให้ข้อมูลผิดกฎถูกบันทึกลงไปได้เลย
--
-- ขอบเขตของ CHECK นี้คือ **รูปแบบ** เท่านั้น (ตัวเลขล้วน และความยาวตามมาตรฐาน
-- GTIN: EAN-8 = 8 · UPC-A = 12 · EAN-13 = 13) ส่วน check digit ตรวจที่ชั้นแอป
-- (database/src/gtin.ts) เพราะเขียนเป็นนิพจน์ SQL แล้วอ่านยากและแก้ยากกว่ามาก
--
-- ความ "ไม่ซ้ำ" มาจาก unique index ของคอลัมน์ barcode ที่มีอยู่แล้วตั้งแต่ migration init
-- (NULL ซ้ำกันได้ตามมาตรฐาน SQL → สินค้าที่ยังไม่มีบาร์โค้ดหลายตัวจึงอยู่ร่วมกันได้)

ALTER TABLE "ProductVariant"
  ADD CONSTRAINT "ProductVariant_barcode_format"
  CHECK ("barcode" IS NULL OR "barcode" ~ '^([0-9]{8}|[0-9]{12}|[0-9]{13})$');
